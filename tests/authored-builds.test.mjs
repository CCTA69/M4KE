import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {mkdtemp,mkdir,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createAuthoredBuilds} from '../server/authored-builds.mjs';

test('authored package is read-only, allowlisted, and integrity checked',async t=>{
  const root=await mkdtemp(path.join(tmpdir(),'m4ke-authored-'));
  const dir=path.join(root,'builds/echo-f1-v1');
  await mkdir(path.join(dir,'print'),{recursive:true});
  const bytes=Buffer.from('fixture STL bytes, not a real mesh');
  const hash=createHash('sha256').update(bytes).digest('hex');
  await writeFile(path.join(dir,'print/chassis.stl'),bytes);
  await writeFile(path.join(dir,'private.txt'),'must not be exposed');
  await writeFile(path.join(dir,'instructions.html'),'<h1>Guide</h1>');
  await writeFile(path.join(dir,'manifest.json'),JSON.stringify({packageStatus:'READY_FOR_FIT_CHECK',cadParts:[],printParts:[{file:'print/chassis.stl',sha256:hash}]}));
  const handler=createAuthoredBuilds(root);
  const server=createServer(async(req,res)=>{
    if(!await handler(req,res,new URL(req.url,'http://localhost').pathname)){res.writeHead(404);res.end();}
  });
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  t.after(async()=>{await new Promise(r=>server.close(r));await rm(root,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/api/authored-builds/echo-f1-v1`;
  assert.equal((await fetch(base)).status,200);
  const cnDir=path.join(root,'builds/echo-f1-cn-v2');
  await mkdir(cnDir,{recursive:true});
  await mkdir(path.join(cnDir,'plates'),{recursive:true});
  const plateName='ECHO-F1-CN-v2-h2c-0.4-PLA.3mf';
  await writeFile(path.join(cnDir,'plates',plateName),bytes);
  await writeFile(path.join(cnDir,'plates','EMBER-BODY.3mf'),bytes);
  await writeFile(path.join(cnDir,'manifest.json'),JSON.stringify({id:'echo-f1-cn-v2',packageStatus:'READY_FOR_FIT_CHECK',cadParts:[],printParts:[],appearance:{artifacts:[{file:'plates/EMBER-BODY.3mf',sha256:hash},{file:'../private.3mf',sha256:hash}]},printPlan:{projects:[{file:'plates/'+plateName,sha256:hash,plates:[]},{file:'../private.3mf',sha256:hash},{file:'plates/../private.3mf',sha256:hash}]}}));
  const cn=await fetch(base.replace('echo-f1-v1','echo-f1-cn-v2'));
  assert.equal(cn.status,200);assert.equal((await cn.json()).id,'echo-f1-cn-v2');
  const plateUrl=base.replace('echo-f1-v1','echo-f1-cn-v2')+'/files/plates/'+plateName;
  const plate=await fetch(plateUrl);assert.equal(plate.status,200);assert.equal(plate.headers.get('content-type'),'model/3mf');
  assert.match(plate.headers.get('content-disposition'),/attachment/);
  const finishUrl=plateUrl.replace(plateName,'EMBER-BODY.3mf');
  assert.equal((await fetch(finishUrl)).status,200);
  await writeFile(path.join(cnDir,'plates','EMBER-BODY.3mf'),'changed');
  assert.equal((await fetch(finishUrl)).status,409,'Colour projects must also be hash checked');
  await writeFile(path.join(cnDir,'plates',plateName),'stale');assert.equal((await fetch(plateUrl)).status,409);
  assert.equal((await fetch(plateUrl.replace(plateName,'not-listed.3mf'))).status,404);
  assert.equal((await fetch(base.replace('echo-f1-v1','echo-f1-cn-v3'))).status,404,'Build IDs remain explicitly allowlisted');
  assert.equal((await fetch(base,{method:'POST'})).status,405);
  const stl=await fetch(base+'/files/print/chassis.stl');
  assert.equal(stl.status,200);assert.deepEqual(Buffer.from(await stl.arrayBuffer()),bytes);
  const head=await fetch(base+'/files/print/chassis.stl',{method:'HEAD'});
  assert.equal(head.status,200);assert.equal((await head.arrayBuffer()).byteLength,0);
  for(const name of ['private.txt','../private.txt','%2e%2e%2fprivate.txt','.env','print/%2e%2e/private.txt'])assert.equal((await fetch(base+'/files/'+name)).status,404);
  const guide=await fetch(base+'/files/instructions.html');
  assert.equal(guide.status,200);assert.match(guide.headers.get('content-security-policy'),/sandbox/);
  await writeFile(path.join(dir,'print/chassis.stl'),'tampered');
  assert.equal((await fetch(base+'/files/print/chassis.stl')).status,409);
  await writeFile(path.join(dir,'manifest.json'),JSON.stringify({cadParts:[],printParts:[]}));
  assert.equal((await fetch(base)).status,409,'Incomplete builds must not offer stale packages');
});
