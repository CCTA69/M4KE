import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const base=process.env.ECHO_URL||'http://127.0.0.1:4176';
const out='.setup/wiring-ui';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.ECHO_BROWSER||'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[],bad=[],writes=[];let meshRequests=0;
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)bad.push([r.status(),r.url()]);});
page.on('request',r=>{if(r.url().endsWith('.stl'))meshRequests++;if(!['GET','HEAD'].includes(r.method()))writes.push(r.url());});
try{
  const manifest=await (await page.request.get(base+'/api/authored-builds/echo-f1-v1')).json();
  await page.goto(base+'/?build=echo-f1-v1&view=wiring');
  await page.waitForFunction(()=>{const v=document.querySelector('.studio-viewport');return v&&v.dataset.nativeTotal==='40'&&v.dataset.nativeLoaded==='40';},{},{timeout:120000});
  assert.equal(await page.getByRole('region',{name:'交互接线图'}).count(),1);
  assert.equal(await page.locator('[data-diagram-wire]').count(),22);
  assert.equal(await page.locator('.echo-wire-list button').count(),22);
  assert.match(await page.locator('.wire-detail').innerText(),/W01/);
  const downloads=meshRequests;
  await page.locator('.viewport-canvas canvas').evaluate(c=>{c.dataset.wiringTest='same-renderer';});
  await page.locator('.echo-wire-list button').filter({hasText:'W12'}).click();
  assert.match(await page.locator('.wire-detail').innerText(),/GPIO34/);
  assert.match(await page.locator('.wire-detail').innerText(),/100kΩ/);
  assert.equal(await page.locator('[data-diagram-wire="W12"]').getAttribute('aria-pressed'),'true');
  await page.screenshot({path:out+'/diagram.png'});
  await page.locator('[data-diagram-wire="W17"]').focus();await page.keyboard.press('Enter');
  assert.match(await page.locator('.wire-detail').innerText(),/100nF/);
  await page.getByRole('button',{name:'下一条线路',exact:true}).click();
  assert.match(await page.locator('.wire-detail').innerText(),/W18/);
  await page.getByRole('group',{name:'线路分类'}).getByRole('button',{name:'信号',exact:true}).click();
  assert.equal(await page.locator('.echo-wire-list button').count(),manifest.connections.filter(c=>c.kind==='signal').length);
  await page.getByRole('group',{name:'线路分类'}).getByRole('button',{name:'全部',exact:true}).click();
  await page.locator('.echo-wire-list button').filter({hasText:'W12'}).click();
  await page.getByRole('button',{name:'3D 定位',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.studio-viewport').dataset.wiresVisible==='true');
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-wiring-focus'),'true');
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-selected-wire'),'W12');
  assert.equal(await page.locator('.echo-routing-note').getAttribute('data-route-ready'),'true');
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-wire-count'),'22');
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-hidden-ids'),'body_shell,canopy');
  assert.match(await page.locator('.echo-routing-note').innerText(),/并非真实焊脚/);
  await page.waitForTimeout(300);
  await page.screenshot({path:out+'/3d.png'});
  await page.getByRole('button',{name:'顶视图',exact:true}).click();
  await page.waitForTimeout(300);
  await page.screenshot({path:out+'/3d-top-open.png'});
  await page.getByRole('button',{name:'合上外壳',exact:true}).click();
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-hidden-ids'),'');
  await page.waitForTimeout(300);
  await page.screenshot({path:out+'/3d-top-closed.png'});
  await page.getByRole('button',{name:'开壳查看',exact:true}).click();
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-hidden-ids'),'body_shell,canopy');
  await page.getByRole('button',{name:'清晰接线图',exact:true}).click();
  await page.getByRole('button',{name:'设计总览',exact:true}).click();
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-wiring-focus'),'false');
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-hidden-ids'),'');
  assert.equal(await page.locator('.viewport-canvas canvas').getAttribute('data-wiring-test'),'same-renderer');
  assert.equal(meshRequests,downloads,'Wiring selection/filter/views must not reload native geometry');
  await page.getByRole('button',{name:'电气接线',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:out+'/mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(await (await page.request.get(base+'/api/authored-builds/echo-f1-v1')).json(),manifest,'Display changes must not mutate package metadata or hashes');
  assert.deepEqual(errors,[]);assert.deepEqual(bad,[]);assert.deepEqual(writes,[]);
  await writeFile(out+'/result.json',JSON.stringify({status:'PASS',connections:22,keyboardSelection:true,filters:true,endpointNotes:true,checkedDisplayRoutes:22,virtualPortsDisclosed:true,coverVisibilityReversible:true,sameRenderer:true,stlReloads:meshRequests-downloads,manifestUnchanged:true,errors,bad,writes},null,2));
  console.log('PASS: wiring diagram, keyboard/click selection, filters, exact endpoint notes, 3D focus, one renderer, zero STL reloads, unchanged manifest, responsive page.');
}finally{await browser.close();}
