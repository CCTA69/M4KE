import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const base=process.env.ECHO_URL||'http://127.0.0.1:4176';
const out='builds/echo-f1-v1/checks';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:process.env.ECHO_BROWSER||'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1600,height:1000},deviceScaleFactor:1});
const errors=[],badResponses=[];let meshRequests=0;
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)badResponses.push([r.status(),r.url()]);});
page.on('request',r=>{if(r.url().endsWith('.stl'))meshRequests++;});
try{
  await page.goto(base+'/?build=echo-f1-v1');
  await page.waitForFunction(()=>{const e=document.querySelector('.studio-viewport');return e&&Number(e.dataset.nativeTotal)>0&&e.dataset.nativeLoaded===e.dataset.nativeTotal;},{},{timeout:120000});
  assert.equal(await page.locator('.viewport-error').count(),0);
  await page.getByRole('button',{name:'显示建议电气接线',exact:true}).click();
  await page.screenshot({path:'builds/echo-f1-v1/preview.png'});
  const downloads=meshRequests;
  await page.getByRole('button',{name:'打开外壳',exact:true}).click();
  assert.match(await page.locator('.studio-viewport').getAttribute('data-hidden-ids'),/body_shell/);
  await page.locator('.echo-outliner button').filter({hasText:'ESP32-DevKitC V4'}).click();
  assert.match(await page.locator('.echo-inspector').innerText(),/GPIO34/);
  await page.getByRole('button',{name:'显示全部零件',exact:true}).click();
  assert.equal(meshRequests,downloads,'Selection and visibility must not reload STL');
  await page.getByRole('button',{name:'跟着装配',exact:true}).click();
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.getByRole('button',{name:'播放装配动画',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('.studio-viewport').dataset.assemblyProgress)===1);
  assert.equal(await page.locator('.echo-step-list button').count(),11);
  await page.screenshot({path:out+'/assembly.png'});
  await page.getByRole('button',{name:'电气接线',exact:true}).click();
  assert.equal(await page.locator('.echo-wire-list button').count(),22);
  await page.locator('.echo-wire-list button').nth(11).click();
  assert.equal(await page.locator('.studio-viewport').getAttribute('data-selected-wire'),'W12');
  await page.getByRole('button',{name:'打印文件',exact:true}).click();
  assert.equal(await page.locator('.echo-printer select').inputValue(),'');
  assert.equal(await page.locator('.echo-print-grid article').count(),17);
  await page.locator('.echo-printer select').selectOption({label:'Bambu Lab A1 mini'});
  assert.match(await page.locator('.echo-warning').innerText(),/不要缩小/);
  await page.getByRole('button',{name:'检查记录',exact:true}).click();
  assert.match(await page.locator('.echo-content').innerText(),/未检测到未解释/);
  for(const f of ['ECHO-F1-build-package.zip','instructions.html','wiring.svg','print/00_fit_coupon.stl'])assert.equal((await page.request.get(base+'/api/authored-builds/echo-f1-v1/files/'+f)).status(),200);
  const guide=await browser.newPage({viewport:{width:1200,height:1000}});
  await guide.goto(base+'/api/authored-builds/echo-f1-v1/files/instructions.html');
  await guide.waitForFunction(()=>Array.from(document.images).length===2&&Array.from(document.images).every(i=>i.complete&&i.naturalWidth>0));
  await guide.screenshot({path:out+'/guide.png'});
  await guide.close();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'设计总览',exact:true}).click();
  await page.screenshot({path:out+'/mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(badResponses,[]);
  await writeFile(out+'/browser.json',JSON.stringify({status:'PASS',nativeParts:40,printedParts:17,assemblySteps:11,wires:22,meshReloadOnSelection:false,errors,badResponses,physicalTest:'NOT_RUN'},null,2));
  console.log('PASS: 40 native meshes; selection/visibility; 11-step playback; 22 wires; 17 STL; printer choice; downloads; no page errors.');
}finally{await browser.close();}
